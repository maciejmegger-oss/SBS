export function talentyEuropy(): TalentEuropy[] {
  return EUROPA_MLODZIEZ.split('\n').map((l) => l.trim()).filter(Boolean).map((l) => {
    const [kraj, kadra, imie, poz, urodz, klub, tmId, tmSlug, wartosc] = l.split('|');
    const czlony = imie.trim().split(/\s+/);
    const lastName = czlony.length > 1 ? czlony[czlony.length - 1] : czlony[0];
    const firstName = czlony.length > 1 ? czlony.slice(0, -1).join(' ') : '';
    return {
      firstName, lastName,
      birthYear: /^\d{4}/.test(urodz || '') ? Number(urodz.slice(0, 4)) : null,
      birthDate: /^\d{4}-\d{2}-\d{2}$/.test(urodz || '') ? urodz : '',
      pozycja: POZYCJE[poz] || poz || '',
      club: klub || '',
      krajKlubu: kraj + ' ' + kadra,
      tmLink: tmId ? 'https://www.transfermarkt.pl/' + tmSlug + '/profil/spieler/' + tmId : '',
      wartosc: wartosc || '',
      europa: true,
    };
  });
}
